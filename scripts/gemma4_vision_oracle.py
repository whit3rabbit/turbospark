#!/usr/bin/env python3
"""Probe mlx-vlm's Gemma 4 vision path and emit Rust golden fixtures.

The reference is PROBED, never transcribed: every number in the generated
files comes from calling the vendored mlx-vlm code, so a fixture cannot
encode this port's own misreading of it (`docs/GEMMA4_VISION_PHASE0.md`).

Run each mode from the repository root:

    uv run --python 3.12 --with mlx --with mlx-vlm --with numpy --with pillow \
      scripts/gemma4_vision_oracle.py preprocess
    uv run --python 3.12 --with mlx --with mlx-vlm --with numpy --with pillow \
      scripts/gemma4_vision_oracle.py tower
    # or `all`

`--mlx-vlm PATH` points at the vendored checkout (default
`../mlx-v/mlx-vlm`). The installed wheel supplies dependencies; the vendored
tree is what gets imported.

`preprocess` runs at the REAL geometry (patch 16, pool 3) because the Rust
side hard-codes it. Large cases commit every Nth sample.

`tower` runs a TINY random tower (hidden 16, 2 heads of 8, 2 blocks, patch 2)
through the real mlx-vlm modules, in float32, and commits the weights, the
inputs and every stage's output. The shapes shrink; the code path does not.
The grid is NON-SQUARE (9 wide, 6 high) so an x/y swap in the rope or the
pooler changes the answer, and a second case appends padding patches that
must not change the pooled rows.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PREPROCESS_OUT = REPO_ROOT / "crates" / "vision-io" / "tests" / "generated" / "gemma4_preprocess_oracle.rs"
TOWER_OUT = REPO_ROOT / "crates" / "compute" / "tests" / "generated" / "gemma4_vision_oracle.rs"

BANNER = """// @generated by scripts/gemma4_vision_oracle.py {mode} -- do not edit by hand.
//
// Probed from the vendored mlx-vlm reference at {source}.
// Regenerate with:
//
//     uv run --python 3.12 --with mlx --with mlx-vlm --with numpy --with pillow \\
//       scripts/gemma4_vision_oracle.py {mode}
"""


def rust_f32_slice(values) -> str:
    import numpy as np

    body = ", ".join(np.format_float_positional(np.float32(v), unique=True) for v in values)
    return f"&[{body}]"


def rust_usize_slice(values) -> str:
    return "&[" + ", ".join(str(int(v)) for v in values) + "]"


def rust_u8_slice(values) -> str:
    return "&[" + ", ".join(str(int(v)) for v in values) + "]"


def write(path: Path, mode: str, source: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(BANNER.format(mode=mode, source=source) + "\n" + body)
    print(f"wrote {path.relative_to(REPO_ROOT)} ({path.stat().st_size} bytes)")


def synth_image(height: int, width: int, seed: int):
    """Deterministic, non-flat, non-noise (H, W, 3) uint8 image."""
    import numpy as np

    y, x = np.mgrid[0:height, 0:width].astype(np.float64)
    r = 128 + 100 * np.sin(x / (3.0 + seed) + y / 7.0)
    g = 128 + 100 * np.cos(y / (5.0 + seed) - x / 11.0)
    b = 128 + 100 * np.sin((x + y) / (4.0 + seed))
    return np.stack([r, g, b], axis=-1).clip(0, 255).astype(np.uint8)


# --------------------------------------------------------------------------
# preprocess
# --------------------------------------------------------------------------


def emit_preprocess(mod, source: Path) -> None:
    import numpy as np

    proc = mod.processing.Gemma4ImageProcessor(patch_size=16, pooling_kernel_size=3)

    # Resize dims only: a zero image of each shape, through the reference's
    # own resize. Covers both zero-side clamps and an identity size.
    dims_cases = [
        (480, 640, 280), (1000, 1000, 70), (10, 4000, 70), (4000, 10, 70),
        (333, 777, 140), (48, 48, 70), (672, 912, 280), (1080, 1920, 560),
        (2048, 1536, 1120), (17, 23, 280),
    ]
    rows = []
    for h, w, budget in dims_cases:
        img = np.zeros((h, w, 3), dtype=np.uint8)
        out, _ = proc.preprocess([img], max_soft_tokens=budget)
        pv = out["pixel_values"]
        pv = pv[0] if isinstance(pv, list) else pv[0]
        rows.append((h, w, budget, pv.shape[1], pv.shape[2]))

    body = ["/// `(src_h, src_w, max_soft_tokens, out_h, out_w)`."]
    body.append("pub const RESIZE_DIMS: &[(usize, usize, usize, usize, usize)] = &[")
    for r in rows:
        body.append(f"    ({r[0]}, {r[1]}, {r[2]}, {r[3]}, {r[4]}),")
    body.append("];")

    # Pixel values: small sources so the bytes can be embedded, resized up to
    # the 70-token budget. Committed every STRIDE-th sample.
    for name, (h, w, seed, budget, stride) in {
        "WIDE": (30, 50, 1, 70, 97),
        "TALL": (64, 40, 2, 70, 89),
    }.items():
        src = synth_image(h, w, seed)
        out, ntok = proc.preprocess([src], max_soft_tokens=budget)
        pv = out["pixel_values"]
        pv = pv[0] if isinstance(pv, list) else pv[0]  # (C, H, W) float32
        flat = np.asarray(pv, dtype=np.float32).reshape(-1)
        body.append(f"\npub const {name}_SRC_HW: (usize, usize) = ({h}, {w});")
        body.append(f"/// Interleaved `(y, x, c)` RGB8.")
        body.append(f"pub const {name}_SRC: &[u8] = {rust_u8_slice(src.reshape(-1))};")
        body.append(f"pub const {name}_BUDGET: usize = {budget};")
        body.append(f"pub const {name}_OUT_HW: (usize, usize) = ({pv.shape[1]}, {pv.shape[2]});")
        body.append(f"pub const {name}_SOFT_TOKENS: usize = {ntok[0]};")
        body.append(f"pub const {name}_STRIDE: usize = {stride};")
        body.append(
            f"/// Reference `pixel_values[0]` in its own `(C, H, W)` order, every "
            f"`{name}_STRIDE`-th element."
        )
        body.append(f"pub const {name}_CHW_SAMPLES: &[f32] = {rust_f32_slice(flat[::stride])};")

    write(PREPROCESS_OUT, "preprocess", source, "\n".join(body) + "\n")


# --------------------------------------------------------------------------
# tower
# --------------------------------------------------------------------------

TINY = dict(
    hidden_size=16,
    intermediate_size=24,
    num_hidden_layers=2,
    num_attention_heads=2,
    num_key_value_heads=2,
    head_dim=8,
    global_head_dim=8,
    patch_size=2,
    pooling_kernel_size=3,
    position_embedding_size=12,
    default_output_length=6,
    standardize=True,
    rms_norm_eps=1e-6,
    rope_parameters={"rope_theta": 100.0, "rope_type": "default"},
)
TEXT_HIDDEN = 20
GRID_W, GRID_H = 9, 6
PADDING = 9


def emit_tower(mod, source: Path) -> None:
    import mlx.core as mx
    import numpy as np

    vision = mod.vision
    cfg = mod.config.VisionConfig(**TINY)
    model = vision.VisionModel(cfg)
    embed = mod.gemma4.MultimodalEmbedder(cfg.hidden_size, TEXT_HIDDEN, eps=cfg.rms_norm_eps)

    rng = np.random.default_rng(20261101)

    def rand(shape, scale=0.4, center=0.0):
        return (center + scale * rng.standard_normal(shape)).astype(np.float32)

    hid, inter, hd, nh = cfg.hidden_size, cfg.intermediate_size, cfg.head_dim, cfg.num_attention_heads
    pdim = 3 * cfg.patch_size ** 2
    weights = {
        "input_proj": rand((hid, pdim)),
        "pos_table": rand((2, cfg.position_embedding_size, hid)),
        "std_bias": rand((hid,), 0.5),
        "std_scale": rand((hid,), 0.2, 1.0),
        "proj": rand((TEXT_HIDDEN, hid)),
    }
    model.patch_embedder.input_proj.weight = mx.array(weights["input_proj"])
    model.patch_embedder.position_embedding_table = mx.array(weights["pos_table"])
    model.std_bias = mx.array(weights["std_bias"])
    model.std_scale = mx.array(weights["std_scale"])
    embed.embedding_projection.weight = mx.array(weights["proj"])

    blocks = []
    for blk in model.encoder.layers:
        w = {
            "ln_in": rand((hid,), 0.2, 1.0),
            "q": rand((nh * hd, hid)),
            "k": rand((nh * hd, hid)),
            "v": rand((nh * hd, hid)),
            "q_norm": rand((hd,), 0.2, 1.0),
            "k_norm": rand((hd,), 0.2, 1.0),
            "o": rand((hid, nh * hd)),
            "ln_post_attn": rand((hid,), 0.2, 1.0),
            "ln_pre_ffw": rand((hid,), 0.2, 1.0),
            "gate": rand((inter, hid)),
            "up": rand((inter, hid)),
            "down": rand((hid, inter)),
            "ln_post_ffw": rand((hid,), 0.2, 1.0),
        }
        blk.input_layernorm.weight = mx.array(w["ln_in"])
        blk.self_attn.q_proj.linear.weight = mx.array(w["q"])
        blk.self_attn.k_proj.linear.weight = mx.array(w["k"])
        blk.self_attn.v_proj.linear.weight = mx.array(w["v"])
        blk.self_attn.q_norm.weight = mx.array(w["q_norm"])
        blk.self_attn.k_norm.weight = mx.array(w["k_norm"])
        blk.self_attn.o_proj.linear.weight = mx.array(w["o"])
        blk.post_attention_layernorm.weight = mx.array(w["ln_post_attn"])
        blk.pre_feedforward_layernorm.weight = mx.array(w["ln_pre_ffw"])
        blk.mlp.gate_proj.linear.weight = mx.array(w["gate"])
        blk.mlp.up_proj.linear.weight = mx.array(w["up"])
        blk.mlp.down_proj.linear.weight = mx.array(w["down"])
        blk.post_feedforward_layernorm.weight = mx.array(w["ln_post_ffw"])
        blocks.append(w)

    n = GRID_W * GRID_H
    pixels = rng.uniform(0.0, 1.0, (n, pdim)).astype(np.float32)
    gx, gy = np.meshgrid(np.arange(GRID_W), np.arange(GRID_H), indexing="xy")
    positions = np.stack([gx.reshape(-1), gy.reshape(-1)], axis=-1).astype(np.int32)

    def run(px, pos):
        px_m = mx.array(px)[None]
        pos_m = mx.array(pos)[None]
        pad = mx.all(pos_m == -1, axis=-1)
        stages = {}
        h = model.patch_embedder.embed_patches(px_m, pos_m, pad)
        stages["patch_embed"] = h
        valid = ~pad
        m = mx.expand_dims(valid, 1) * mx.expand_dims(valid, 2)
        m = mx.expand_dims(mx.where(m, mx.array(0.0), mx.array(-1e4)), 1)
        for i, layer in enumerate(model.encoder.layers):
            h = layer(h, pos_m, m)
            stages[f"block_{i}"] = h
        out = model(px_m, pos_m)  # the whole tower, as mlx-vlm's caller runs it
        stages["tower"] = out
        stages["embedded"] = embed(out)
        return {k: np.asarray(v[0], dtype=np.float32) for k, v in stages.items()}

    plain = run(pixels, positions)
    pad_px = np.concatenate([pixels, np.zeros((PADDING, pdim), np.float32)])
    pad_pos = np.concatenate([positions, np.full((PADDING, 2), -1, np.int32)])
    # 63 rows pools to 7 soft tokens by the reference's own arithmetic, one of
    # them empty, which mlx-vlm then strips. Only the shape that survives is
    # compared.
    padded = run(pad_px, pad_pos)

    b = []
    b.append(f"pub const HIDDEN: usize = {hid};")
    b.append(f"pub const INTERMEDIATE: usize = {inter};")
    b.append(f"pub const HEADS: usize = {nh};")
    b.append(f"pub const HEAD_DIM: usize = {hd};")
    b.append(f"pub const BLOCKS: usize = {cfg.num_hidden_layers};")
    b.append(f"pub const PATCH_DIM: usize = {pdim};")
    b.append(f"pub const POS_TABLE_ROWS: usize = {cfg.position_embedding_size};")
    b.append(f"pub const POOL: usize = {cfg.pooling_kernel_size};")
    b.append(f"pub const TEXT_HIDDEN: usize = {TEXT_HIDDEN};")
    b.append(f"pub const ROPE_THETA: f32 = {cfg.rope_parameters['rope_theta']};")
    b.append(f"pub const EPS: f32 = {cfg.rms_norm_eps};")
    b.append(f"pub const GRID_WH: (usize, usize) = ({GRID_W}, {GRID_H});")
    b.append("")
    b.append("/// `[n, PATCH_DIM]` in `[0, 1]`, row-major over the grid.")
    b.append(f"pub const PIXELS: &[f32] = {rust_f32_slice(pixels.reshape(-1))};")
    b.append("/// `(x, y)` flattened.")
    b.append(f"pub const POSITIONS: &[usize] = {rust_usize_slice(positions.reshape(-1))};")
    b.append("")
    for k, v in weights.items():
        b.append(f"pub const W_{k.upper()}: &[f32] = {rust_f32_slice(v.reshape(-1))};")
    b.append("")
    b.append("/// Per block, in `BLOCK_ROLES` order.")
    roles = list(blocks[0].keys())
    b.append("pub const BLOCK_ROLES: &[&str] = &[" + ", ".join(f'"{r}"' for r in roles) + "];")
    b.append("pub const BLOCK_WEIGHTS: &[&[&[f32]]] = &[")
    for w in blocks:
        b.append("    &[")
        for r in roles:
            b.append(f"        {rust_f32_slice(w[r].reshape(-1))},")
        b.append("    ],")
    b.append("];")
    b.append("")
    for k, v in plain.items():
        b.append(f"/// Stage `{k}`, shape {list(v.shape)}.")
        b.append(f"pub const OUT_{k.upper()}: &[f32] = {rust_f32_slice(v.reshape(-1))};")
    b.append("")
    b.append(f"pub const PADDING: usize = {PADDING};")
    b.append(f"/// The padded run's `tower` stage, shape {list(padded['tower'].shape)}.")
    b.append(f"pub const PADDED_OUT_TOWER: &[f32] = {rust_f32_slice(padded['tower'].reshape(-1))};")

    write(TOWER_OUT, "tower", source, "\n".join(b) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("mode", choices=["preprocess", "tower", "all"])
    parser.add_argument(
        "--mlx-vlm",
        default=str(REPO_ROOT.parent / "mlx-v" / "mlx-vlm"),
        help="the vendored mlx-vlm checkout to import from",
    )
    args = parser.parse_args()

    vendored = Path(args.mlx_vlm).resolve()
    if not (vendored / "mlx_vlm").is_dir():
        raise SystemExit(f"no mlx_vlm package under {vendored}")
    sys.path.insert(0, str(vendored))

    import importlib
    import types

    base = "mlx_vlm.models.gemma4"
    mod = types.SimpleNamespace(
        processing=importlib.import_module(f"{base}.processing_gemma4"),
        vision=importlib.import_module(f"{base}.vision"),
        config=importlib.import_module(f"{base}.config"),
        gemma4=importlib.import_module(f"{base}.gemma4"),
    )
    source = vendored / "mlx_vlm" / "models" / "gemma4"
    if args.mode in ("preprocess", "all"):
        emit_preprocess(mod, source)
    if args.mode in ("tower", "all"):
        emit_tower(mod, source)


if __name__ == "__main__":
    main()
