#!/usr/bin/env python3
"""Regenerate the Unsloth IQ1_XS / IQ1_XXS / IQ1_XXXS grid tables.

These three ggml types exist only in Unsloth's llama.cpp fork (branch
`iq1-narrow-grids-b10775`, ggml type ids 64 to 66). Each uses IQ1_S's
8-dimensional ternary codebook with a narrower index, so each carries its own
`uint64_t iq1_*_grid[]` in `ggml/src/ggml-common.h`. This extracts them.

usage: gen_iq1_narrow_grids.py <path to the fork's ggml-common.h> \
           > crates/compute/src/quant_gguf_iq1_narrow_tables.rs
       gen_iq1_narrow_grids.py <path to ggml-common.h> --metal \
           > crates/gpu/src/shaders/dequant_iq1_narrow_tables.metal
"""
import re
import sys

src = open(sys.argv[1]).read()
metal = "--metal" in sys.argv
TABLES = [
    ("iq1_xs_grid", "IQ1_XS_GRID", 1024),
    ("iq1_xxs_grid", "IQ1_XXS_GRID", 512),
    ("iq1_xxxs_grid", "IQ1_XXXS_GRID", 256),
]
print("// GENERATED by scripts/gen_iq1_narrow_grids.py from the Unsloth llama.cpp fork's")
print("// ggml/src/ggml-common.h (branch iq1-narrow-grids-b10775). Do not edit.")
print()
for cname, rname, n in TABLES:
    m = re.search(
        r"GGML_TABLE_BEGIN\(uint64_t, %s, \w+\)(.*?)GGML_TABLE_END\(\)" % cname, src, re.S
    )
    vals = re.findall(r"0x[0-9a-fA-F]+", m.group(1))
    assert len(vals) == n, (cname, len(vals), n)
    if metal:
        print("constant constexpr ulong k%sTable[%d] = {" % (rname.title().replace("_", ""), n))
        for i in range(0, n, 4):
            print("    " + ", ".join("%sul" % v for v in vals[i : i + 4]) + ",")
        print("};\n")
    else:
        print("pub const %s: [u64; %d] = [" % (rname, n))
        for i in range(0, n, 4):
            print("    " + ", ".join("%su64" % v for v in vals[i : i + 4]) + ",")
        print("];\n")
