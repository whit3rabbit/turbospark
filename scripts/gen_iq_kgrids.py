#!/usr/bin/env python3
"""Regenerate crates/repack/src/gguf_quantize/iq_kgrid_tables.rs.

The IQ quantizers search ggml's compressed grids (`kgrid_*` in
ggml/src/ggml-quants.c, inside iq2xs_init_impl and iq3xs_init_impl). They are
not the dequantization grids that crates/compute carries, so they are
extracted from the ggml source instead of copied by hand.

usage: gen_iq_kgrids.py <path to ggml-quants.c> > crates/repack/src/gguf_quantize/iq_kgrid_tables.rs
"""
import re
import sys

src = open(sys.argv[1]).read()
NAMES = [
    ("kgrid_2bit_256", "KGRID_2BIT_256", 256),
    ("kgrid_2bit_512", "KGRID_2BIT_512", 512),
    ("kgrid_1bit_2048", "KGRID_1BIT_2048", 2048),
    ("kgrid_2bit_1024", "KGRID_2BIT_1024", 1024),
    ("kgrid_256", "KGRID_3BIT_256", 256),
    ("kgrid_512", "KGRID_3BIT_512", 512),
]
print("//! GENERATED by scripts/gen_iq_kgrids.py from ggml/src/ggml-quants.c. Do not edit.")
print("//! Each entry packs one grid point: 2 bits per value for the IQ2/IQ1 grids")
print("//! (8 values) and 3 bits per value for the IQ3 grids (4 values).")
print()
for cname, rname, n in NAMES:
    m = re.search(r"static const uint16_t %s\[[^\]]*\]\s*=\s*\{(.*?)\};" % cname, src, re.S)
    vals = [int(v) for v in re.findall(r"\d+", m.group(1))]
    assert len(vals) == n, (cname, len(vals), n)
    print("pub const %s: [u16; %d] = [" % (rname, n))
    for i in range(0, n, 16):
        print("    " + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    print("];\n")
