"""Writes the Drama 3 pause guard's voiced-code table from probe output.

usage: python3 -I scripts/fish_drama3_voiced_table.py OUT.rs PROBE.jsonl [PROBE.jsonl ...]

Reads the JSON lines of crates/runtime/examples/fish_drama3_silence_probe.rs
(one per main draw: the main code `c0` and the decoded RMS of its frame) and
marks a code voiced when fewer than half of the frames that drew it are silent
(RMS under -45 dBFS, the runner's rule). Every other code, silent-majority or
never drawn, counts as silent to the guard. The table is written as a Rust
source file, `audio::tts::fish_drama3::voiced`.

The run behind the shipped table and its limits are in
docs/FISH_DRAMA3_PHASE0.md (Pause guard).
"""
import json
import sys
from collections import defaultdict

SILENT_DB = -45.0
CODES = 4096
WORD = 64

out_path = sys.argv[1]
inputs = sys.argv[2:]
if not inputs:
    sys.exit(__doc__)

counts = defaultdict(lambda: [0, 0])  # c0 -> [frames, silent frames]
takes = set()
frames = 0
for path in inputs:
    with open(path) as f:
        for line in f:
            row = json.loads(line)
            c0 = row["c0"]
            if c0 < 0 or row["rms_db"] is None:
                continue
            if not 0 <= c0 < CODES:
                sys.exit(f"{path}: code {c0} is outside the {CODES}-code band")
            takes.add((path, row["case"], row["seed"]))
            frames += 1
            counts[c0][0] += 1
            counts[c0][1] += row["rms_db"] < SILENT_DB

voiced = sorted(c for c, (n, s) in counts.items() if 2 * s < n)
words = [0] * (CODES // WORD)
for c in voiced:
    words[c // WORD] |= 1 << (c % WORD)

lines = [
    "//! The Drama 3 pause guard's voiced-code table. Generated by",
    "//! `scripts/fish_drama3_voiced_table.py`. Do not edit by hand.",
    "//!",
    f"//! From {len(takes)} takes and {frames} frames of",
    "//! `crates/runtime/examples/fish_drama3_silence_probe.rs` on",
    "//! `crates/audio/testdata/fish_drama3/voiced_table_corpus.txt`. Bit",
    "//! `c0 % 64` of word `c0 / 64` is set when fewer than half of the frames",
    "//! that drew semantic code `c0` decoded under -45 dBFS. The guard counts",
    f"//! every other code as silent, including the {CODES - len(counts)} the run never drew.",
    "//! `docs/FISH_DRAMA3_PHASE0.md` (Pause guard) has the run and its limits.",
    "",
    "/// Semantic codes read as voiced, one bit per code.",
    f"pub const VOICED: [u64; {CODES // WORD}] = [",
]
lines += [f"    0x{w:016x}," for w in words]
lines += [
    "];",
    "",
    "/// Codes set in [`VOICED`], so a test can catch a hand edit.",
    f"pub const VOICED_CODES: u32 = {len(voiced)};",
    "",
]
with open(out_path, "w") as f:
    f.write("\n".join(lines))
print(
    f"{len(takes)} takes, {frames} frames, {len(counts)} codes drawn, "
    f"{len(voiced)} voiced -> {out_path}"
)
