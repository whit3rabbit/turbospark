#!/usr/bin/env python3
"""Write `crates/vision-io/tests/generated/inkling2_preprocess_oracle.rs` from
the numpy transcription's `preprocess` (`scripts/inkling2_vision_reference.py`).

The source pixels are a closed-form pattern generated identically here and in
the Rust test, so no decoder is involved (see `crates/vision-io/src/decode.rs`
for why). The oracle holds every STRIDE-th tile sample in the reference's own
`[N, 40, 40, 3]` order plus the f64 sum of all of them; the Rust test maps
each sample to its patch row by index arithmetic.

Usage:
    python3 -I scripts/inkling2_preprocess_oracle.py
"""

import importlib.util
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "crates/vision-io/tests/generated/inkling2_preprocess_oracle.rs"
STRIDE = 97


def load_reference():
    spec = importlib.util.spec_from_file_location("ref", HERE / "inkling2_vision_reference.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def pattern(h, w, channels):
    """Sample `(y, x, c)`: `(x * 7 + y * 13 + c * 61 + (x * y) % 17) % 256`."""
    y, x, c = np.meshgrid(np.arange(h), np.arange(w), np.arange(channels), indexing="ij")
    return ((x * 7 + y * 13 + c * 61 + (x * y) % 17) % 256).astype(np.uint8)


CASES = [
    # name, height, width, channels
    ("RGB_83X121", 83, 121, 3),
    ("RGBA_45X63", 45, 63, 4),
    ("RGB_40X40", 40, 40, 3),
]


def main():
    ref = load_reference()
    lines = [
        "// @generated by scripts/inkling2_preprocess_oracle.py -- do not edit by hand.",
        "//",
        "// From the numpy transcription of transformers' Inkling2ImageProcessor",
        "// (scripts/inkling2_vision_reference.py `preprocess`). Regenerate with:",
        "//",
        "//     python3 -I scripts/inkling2_preprocess_oracle.py",
        "",
        f"pub const STRIDE: usize = {STRIDE};",
        "",
    ]
    for name, h, w, ch in CASES:
        tiles, r, c = ref.preprocess(pattern(h, w, ch))
        flat = tiles.reshape(-1)
        picks = flat[::STRIDE]
        lines.append(f"/// `{h}x{w}`, {ch} channels: tile grid, every STRIDE-th tile sample, sum.")
        lines.append(f"pub const {name}_SRC: (usize, usize, usize) = ({h}, {w}, {ch});")
        lines.append(f"pub const {name}_GRID: (usize, usize) = ({r}, {c});")
        # The shortest spelling that round-trips as f32 (numpy's float32
        # repr), so the literal is exactly the sample and clippy's
        # excessive_precision has nothing to flag.
        def lit(v):
            t = str(np.float32(v))
            return t if any(mark in t for mark in ".eE") else t + ".0"

        body = ", ".join(lit(v) for v in picks)
        lines.append(f"pub const {name}_SAMPLES: &[f32] = &[{body}];")
        lines.append(f"pub const {name}_SUM: f64 = {float(flat.astype(np.float64).sum())!r};")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(OUT)


if __name__ == "__main__":
    main()
