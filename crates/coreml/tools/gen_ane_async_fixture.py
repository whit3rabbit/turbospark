"""Generate a tiny 4D shared-plane fixture, using coremltools 9.0.

uv run --python 3.12 --with coremltools==9.0 --with numpy==2.2.6 \
    python -I crates/coreml/tools/gen_ane_async_fixture.py OUTPUT.mlpackage
"""
import sys
import coremltools as ct
import numpy as np
from coremltools.converters.mil import Builder as mb
from coremltools.converters.mil.mil import types

@mb.program(input_specs=[mb.TensorSpec((1, 1, 2, 32), types.fp16)],
            opset_version=ct.target.macOS13)
def program(x):
    return mb.add(x=x, y=x, name="y")

ct.convert(program, convert_to="mlprogram", minimum_deployment_target=ct.target.macOS13,
           compute_precision=ct.precision.FLOAT16).save(sys.argv[1])

# Record the generated bytes independently of the standing fixture corpus.
from pathlib import Path
import hashlib
import json
root = Path(sys.argv[1])
weights = root / 'Data/com.apple.CoreML/weights'
weights.mkdir(exist_ok=True)
(weights / '.gitkeep').touch()
hash_value = hashlib.sha256()
for file in sorted(root.rglob('*')):
    if file.is_file():
        hash_value.update(str(file.relative_to(root)).encode())
        hash_value.update(file.read_bytes())
root.with_suffix('.manifest.json').write_text(json.dumps({
    'generator': 'crates/coreml/tools/gen_ane_async_fixture.py',
    'coremltools': ct.__version__, 'numpy': np.__version__,
    'sha256_tree': hash_value.hexdigest()}, indent=2) + '\n')
