/// In-range lookup over one sorted inclusive range table.
fn in_ranges(table: &[(u32, u32)], code: u32) -> bool {
    table
        .binary_search_by(|&(start, end)| {
            if code < start {
                std::cmp::Ordering::Greater
            } else if code > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// `_get_char_weight`: the weight of one character.
pub(crate) fn char_weight(ch: char) -> f64 {
    let code = ch as u32;
    // ASCII letters and the plain space dominate input; the reference
    // checks them first.
    if (0x41..=0x5a).contains(&code) || (0x61..=0x7a).contains(&code) {
        return LATIN;
    }
    if code == 0x20 {
        return SPACE;
    }
    // The Arabic tatweel is silent.
    if code == 0x0640 {
        return MARK;
    }
    if in_ranges(MARK_RANGES, code) {
        return MARK;
    }
    if in_ranges(PUNCT_RANGES, code) || in_ranges(SYMBOL_RANGES, code) {
        return PUNCTUATION;
    }
    if in_ranges(SPACE_Z_RANGES, code) {
        return SPACE;
    }
    if in_ranges(NUMBER_RANGES, code) {
        return DIGIT;
    }
    // The range table is (end, weight) pairs sorted ascending; the FIRST
    // end at or past the code owns it (the reference bisect_left gives
    // the same first match, and a later row would misclassify).
    let index = SCRIPT_RANGES.partition_point(|&(end, _)| end < code);
    if let Some(&(_, weight)) = SCRIPT_RANGES.get(index) {
        return weight;
    }
    // Upper planes: CJK Extension B/C/D and historic scripts.
    if code > 0x20000 {
        return CJK;
    }
    DEFAULT
}

/// `calculate_total_weight`: the sum over the string, accumulated in the
/// reference's left-to-right order.
pub(crate) fn total_weight(text: &str) -> f64 {
    text.chars().map(char_weight).sum()
}

/// `RuleDurationEstimator.estimate_duration`: scale the reference clip's
/// measured duration by the relative character weights, with the
/// power-curve boost for very short estimates.
pub fn estimate_duration(
    target_text: &str,
    ref_text: &str,
    ref_duration: f64,
    low_threshold: Option<f64>,
    boost_strength: f64,
) -> f64 {
    if ref_duration <= 0.0 || ref_text.is_empty() {
        return 0.0;
    }
    let ref_weight = total_weight(ref_text);
    if ref_weight == 0.0 {
        return 0.0;
    }
    let speed_factor = ref_weight / ref_duration;
    let target_weight = total_weight(target_text);
    let estimated = target_weight / speed_factor;
    match low_threshold {
        Some(low) if estimated < low => low * (estimated / low).powf(1.0 / boost_strength),
        _ => estimated,
    }
}

